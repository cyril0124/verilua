# -- Multi (beat_num >= 3) ----------------------------------------------------

def _beat_branches(vpi_prefix: str, hdl_expr: str) -> str:
    """`if/elseif` chain dispatching beat_num 3..8 to a fixed-arity vpiml call."""
    branches = []
    for n in range(3, 9):
        args = ", ".join("value[%d]" % i for i in range(1, n + 1))
        kw = "if" if n == 3 else "elseif"
        branches.append(
            "        %s beat_num == %d then\n            vpiml.%s_multi_beat_%d(%s, %s)"
            % (kw, n, vpi_prefix, n, hdl_expr, args)
        )
    return "\n".join(branches)


def gen_multi_set_dispatch(vpi_prefix: str, hdl_expr: str = "this.hdl") -> str:
    """Table branch of a safe setter: validates type and beat count."""
    return """        if t ~= "table" then assert(false, "set() expects number, uint64_t, or table; got " .. t .. ", fullpath => " .. this.fullpath) end
        local beat_num = this.beat_num
        if #value ~= beat_num then assert(false, "len: " .. #value .. " =/= " .. this.beat_num) end

%s
        else
            for i = 1, this.beat_num do
                this.c_results[i - 1] = value[i]
            end
            vpiml.%s_multi(%s, this.c_results)
        end""" % (_beat_branches(vpi_prefix, hdl_expr), vpi_prefix, hdl_expr)


def gen_multi_set_unsafe_dispatch(vpi_prefix: str, hdl_expr: str = "this.hdl") -> str:
    """Same as above without the type/length checks, for hot paths."""
    return """        local beat_num = this.beat_num
%s
        else
            for i = 1, this.beat_num do
                this.c_results[i - 1] = value[i]
            end
            vpiml.%s_multi(%s, this.c_results)
        end""" % (_beat_branches(vpi_prefix, hdl_expr), vpi_prefix, hdl_expr)


