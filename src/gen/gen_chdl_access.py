#!/usr/bin/env python3
"""Generate ChdlAccess{Single,Double,Multi}.lua.

Verilua drives hardware signals of different widths through three access
variants, selected by how many 32-bit beats a signal needs:

    Single  beat_num == 1   (1-32 bit)
    Double  beat_num == 2   (33-64 bit)
    Multi   beat_num >= 3   (> 64 bit)

Splitting them keeps each variant free of runtime width checks. Every method is
built once at module load time and shared by all handle instances, so call
sites stay monomorphic and the JIT can specialize on the concrete type.

Usage: ./gen_chdl_access.py
"""

